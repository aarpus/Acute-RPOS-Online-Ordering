import assert from 'node:assert/strict';
import { loadMenuModule } from './menu-script-runtime.mjs';
const { comboGroupError, comboOptionError, normalizeComboGroup } = loadMenuModule('lib/combo-master.ts');
const group={id:1,name:'Choose sides',externalId:'',selectionType:'selectable',min:1,max:2,required:true,order:1,options:[]};
const option={id:2,itemId:'item-a',name:'Fries',quantity:1,extraPrice:0,isDefault:false,available:true,order:1,externalId:''};
assert.equal(comboGroupError(group,[]),'','A group must save before its options are created');
assert.match(comboGroupError({...group,min:3},[]),/Maximum picks/);
assert.match(comboGroupError({...group,min:1.5},[]),/whole numbers/);
assert.match(comboGroupError({...group,required:false},[]),/Optional groups/);
assert.match(comboGroupError({...group,name:' '},[]),/name/);
assert.match(comboGroupError({...group,id:3},[group]),/already exists/);
assert.equal(comboOptionError(option,group),'');
assert.equal(comboOptionError({...option,extraPrice:null},group),'','Blank extra price selects automatic item pricing');
assert.equal(comboOptionError({...option,extraPrice:0},group),'','Explicit zero stays free');
assert.match(comboOptionError({...option,id:3},{...group,options:[option]}),/already an option/);
assert.match(comboOptionError({...option,itemId:''},group),/saved regular/);
assert.match(comboOptionError({...option,quantity:0},group),/Quantity/);
assert.match(comboOptionError({...option,extraPrice:-1},group),/Extra price/);
assert.match(comboOptionError({...option,extraPrice:1.001},group),/Extra price/);
assert.match(comboOptionError({...option,id:3,itemId:'item-b',isDefault:true},{...group,max:1,options:[{...option,isDefault:true}]}),/default options/);
const fixed=normalizeComboGroup({...group,selectionType:'fixed',options:[option,{...option,id:3,itemId:'item-b',available:false}]});
assert.equal(fixed.min,1);assert.equal(fixed.max,1);assert.equal(fixed.required,true);assert.equal(fixed.options[0].isDefault,true);assert.equal(fixed.options[1].isDefault,false);
const empty=normalizeComboGroup({...group,selectionType:'fixed'});
assert.equal(empty.min,0);assert.equal(empty.max,0);assert.equal(empty.required,false);
const navigation=loadMenuModule('lib/admin-menu.ts');
assert.equal(navigation.menuSectionForView('combo-items'),'Combo Master');
assert.equal(navigation.menuScreenHref('Combo Master'),'/admin/menu?view=combo-items');
console.log('Passed: Combo Master navigation, group-first creation, pick limits, duplicate groups/items, quantities, prices, defaults and fixed group normalization.');
